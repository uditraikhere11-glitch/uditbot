"""
Interactive CLI Setup Wizard for VM & Local Environments.
Matches the configuration parameters from the visual setup specification:
- Operator Name & Bot Instance Name (Audit bot)
- Exchange Credentials (Dhan Client ID, Access Token / TOTP Secret, PIN)
- Bot Configuration (Operator Name, Instance Name, Monitoring/Log Group ID, Test Group ID)
- Risk Management (Max Drawdown %, Daily Trade Limit, Max Order Amount, Min Funds)
- Sizing Defaults (Equity Budget, Product Type, Options Budget, Max Lots, SL/Target)
- Execution Mode (TEST vs LIVE master switch)
Writes safely to .env with 0600 file permissions.
"""

import os
import sys
from typing import Dict, Any


def prompt(text: str, default: str = "") -> str:
    """Prompts operator with a default value."""
    if default:
        res = input(f"{text} [{default}]: ").strip()
        return res if res else default
    return input(f"{text}: ").strip()


def run_setup_wizard(env_path: str = ".env") -> Dict[str, Any]:
    print("\n" + "=" * 60)
    print("                AUDIT BOT SETUP WIZARD                 ")
    print(" Configure your algorithmic trading parameters & Dhan   ")
    print("=" * 60 + "\n")

    # 1. Operator & Identity
    print("--- [1] Operator & Bot Identity ---")
    operator_name = prompt("Operator / User Name", "Udit")
    instance_name = prompt("Bot Instance Name", "Audit bot")

    # 2. Exchange Credentials
    print("\n--- [2] Exchange Credentials (DhanHQ v2) ---")
    dhan_client_id = prompt("Dhan Client ID (e.g. 1100XXXXXX)", "1000000000")
    dhan_pin = prompt("Dhan 6-digit PIN", "123456")
    dhan_totp_secret = prompt("Dhan TOTP Secret (for daily 08:00 refresh)", "JBSWY3DPEHPK3PXP")
    dhan_access_token = prompt("Dhan Access Token (Optional if using TOTP)", "")

    # 3. Bot Configuration & Telegram
    print("\n--- [3] Telegram Ingestion & Groups ---")
    log_group_id = prompt("Monitoring Group ID / Log Group (e.g. -1004417022099 or -5514889030)", "-5514889030")
    test_group_id = prompt("Test Channel ID (for test signals)", "-5100801652")
    monitored_channels = prompt("Monitored Telegram Channels (comma-separated IDs)", f"-1004417022099, {test_group_id}")
    tg_api_id = prompt("Telegram API ID", "1234567")
    tg_api_hash = prompt("Telegram API Hash", "0123456789abcdef0123456789abcdef")

    # 4. Risk Management
    print("\n--- [4] Risk Management ---")
    max_drawdown_pct = prompt("Max Drawdown / Daily Loss (%)", "5.0")
    daily_trade_limit = prompt("Daily Trade Limit", "20")
    max_order_amount = prompt("Max Order Amount (INR)", "50000")
    min_trade_funds = prompt("Minimum Required Funds (INR)", "10000")
    test_mode_paper_funds = prompt("Virtual Paper Balance for TEST Mode (INR)", "100000")

    # 5. Sizing Defaults
    print("\n--- [5] Sizing & Product Defaults ---")
    equity_budget = prompt("Equity Budget per Trade (INR)", "25000")
    equity_product = prompt("Equity Product Type (CNC or MTF)", "CNC").upper()
    fno_capital = prompt("Stock Options Budget per Trade (INR)", "20000")
    fno_max_lots = prompt("Options Max Lots Cap (0 = no cap)", "3")
    sl_pct = prompt("Default Stop Loss (%)", "3.0")
    target_pct = prompt("Default Target (%)", "3.0")

    # 6. Execution Mode
    print("\n--- [6] Execution Mode ---")
    print("Note: TEST mode runs real-time signal validation, sizing, and logging")
    print("      WITHOUT submitting broker orders or creating fake fills.")
    mode_input = prompt("Operating Mode: (1) TEST [Safe Default], (2) LIVE", "1")
    trading_mode = "LIVE" if mode_input in ("2", "LIVE", "live") else "TEST"

    # Write .env file
    env_content = f"""# =====================================================================
# AUDIT BOT / DHAN ALGO - OPERATOR CONFIGURATION
# Generated by Setup Wizard on {instance_name}
# =====================================================================

# --- OPERATOR & BOT IDENTITY ---
OPERATOR_NAME={operator_name}
BOT_INSTANCE_NAME={instance_name}

# --- OPERATING MODE & PRODUCTS ---
TRADING_MODE={trading_mode}
EQUITY_ACTIVE=true
FNO_ACTIVE=true

# --- EXCHANGE CREDENTIALS (DHANHQ v2) ---
DHAN_CLIENT_ID={dhan_client_id}
DHAN_PIN={dhan_pin}
DHAN_TOTP_SECRET={dhan_totp_secret}
DHAN_ACCESS_TOKEN={dhan_access_token}
DHAN_TOKEN_FILE=~/.dhan_token

# --- BOT CONFIGURATION & TELEGRAM ---
TG_API_ID={tg_api_id}
TG_API_HASH={tg_api_hash}
MONITORED_CHANNEL_IDS={monitored_channels}
TEST_GROUP_ID={test_group_id}
LOG_GROUP_ID={log_group_id}
IGNORE_TELEGRAM_BACKLOG_ON_RESTART=true

# --- RISK MANAGEMENT ---
MAX_DAILY_LOSS_INR=15000
MAX_DRAWDOWN_PCT={max_drawdown_pct}
MAX_DAILY_TRADES={daily_trade_limit}
MAX_ORDER_AMOUNT_INR={max_order_amount}
MIN_TRADE_FUNDS_INR={min_trade_funds}
TEST_MODE_PAPER_FUNDS_INR={test_mode_paper_funds}
MAX_TOTAL_EXPOSURE_INR=150000
MAX_OPEN_POSITIONS=5
INSUFFICIENT_FUNDS_POLICY=HARD_REJECT
MODE_SWITCH_POSITION_POLICY=REMAIN_UNTOUCHED

# --- SIZING & EXECUTION DEFAULTS ---
EQUITY_PRODUCT_TYPE={equity_product}
EQUITY_SIZING_MODE=BUDGET
EQUITY_BUDGET_INR={equity_budget}
EQUITY_PRICE_MARKUP_PCT=0.5

FNO_SIZING_MODE=BUDGET
FNO_CAPITAL_PER_TRADE={fno_capital}
FNO_FIXED_LOTS=1
FNO_MAX_LOTS={fno_max_lots}

# --- PROTECTION & TIMING (FOREVER OCO) ---
SL_PCT={sl_pct}
TARGET_PCT={target_pct}
SL_LIMIT_BUFFER_PCT=1.0
MAX_QUOTE_AGE_SEC=2.0
PARTIAL_FILL_RETRY_TIMEOUT_SEC=2.0
MAX_MESSAGE_AGE_SEC=60.0
DEDUP_WINDOW_SEC=20.0
"""

    fd = os.open(env_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(env_content)

    print("\n" + "=" * 60)
    print(f"✅ Configuration successfully saved to: {env_path}")
    print(f"🔒 File permissions locked to: chmod 0600 {env_path}")
    print(f"👤 Operator: {operator_name}")
    print(f"🤖 Bot Instance: {instance_name}")
    print(f"🚀 Execution Mode is currently set to: {trading_mode}")
    print("=" * 60 + "\n")

    return {"status": "success", "mode": trading_mode, "file": env_path, "operator": operator_name}


if __name__ == "__main__":
    run_setup_wizard()
